// ============================================
// POST /api/export/integrated-skills
// 匯出 Integrated Skills 完整報告 (PDF + DOCX)
// PDF: pdfkit (English-only via Helvetica, no CJK dependency)
// DOCX: docx package (full Unicode support)
// ============================================

import { NextRequest, NextResponse } from 'next/server';
import { logger } from '@/shared/logger/logger';

interface ExportData {
  listeningContent?: string; writingTask?: string; taskType?: string;
  studentNotes?: string; studentWriting?: string;
  analysis?: Record<string, unknown>;
}

// ==================== DOCX ====================
async function generateDOCX(data: ExportData): Promise<Buffer> {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, WidthType, BorderStyle } = await import('docx');
  const children: any[] = [];
  const h1 = (t: string) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(t)], spacing: { before: 300, after: 100 } });
  const h2 = (t: string, c?: string) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: t, color: c || '000000' })], spacing: { before: 200, after: 80 } });
  const p = (t: string, o?: any) => new Paragraph({ children: [new TextRun({ text: t, ...o })], spacing: { after: 80 } });

  children.push(new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun('DSE Integrated Skills Report')], spacing: { after: 100 } }));
  children.push(p('Generated by AI English Platform', { italics: true, color: '888888', size: 20 }));
  children.push(p(''));

  if (data.writingTask) { children.push(h1('Writing Task')); children.push(p(`Type: ${data.taskType || 'N/A'}`)); children.push(p(data.writingTask)); children.push(p('')); }
  if (data.listeningContent) { children.push(h1('Listening Content')); children.push(p(data.listeningContent, { size: 18, color: '666666' })); children.push(p('')); }
  if (data.studentNotes) { children.push(h1('Student Note-taking')); children.push(new Paragraph({ children: [new TextRun(data.studentNotes)], border: { left: { style: BorderStyle.SINGLE, color: 'f59e0b', size: 6 } }, spacing: { after: 200 } })); children.push(p('')); }
  if (data.studentWriting) { children.push(h1('Student Writing')); children.push(new Paragraph({ children: [new TextRun(data.studentWriting)], border: { left: { style: BorderStyle.SINGLE, color: '7c3aed', size: 6 } }, spacing: { after: 200 } })); children.push(p('')); }

  const a = data.analysis;
  if (a) {
    children.push(h1('AI Analysis'));
    const scores: [string, string][] = [
      ['Overall Score', `${a.overallScore}%`], ['Listening Accuracy', `${a.listeningAccuracy ?? '-'}%`],
      ['Content Completeness', `${a.contentCompleteness ?? '-'}%`], ['Language Accuracy', `${a.languageAccuracy ?? '-'}%`],
      ['Organization & Clarity', `${a.organizationClarity ?? '-'}%`],
    ];
    if (a.estimatedLevel) scores.push(['Estimated Level', String(a.estimatedLevel)]);
    children.push(new Table({ rows: scores.map(([l, v]) => new TableRow({ children: [new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: l, bold: true })], spacing: { after: 0 } })], width: { size: 4500, type: WidthType.DXA } }), new TableCell({ children: [new Paragraph({ children: [new TextRun(v)], spacing: { after: 0 } })] })] })), width: { size: 100, type: WidthType.PERCENTAGE } }));
    children.push(p(''));

    const caps = (a.capturedPoints as string[]) || [], miss = (a.missedPoints as string[]) || [];
    if (caps.length) { children.push(h2(`Captured Points (${caps.length})`, '16a34a')); caps.forEach(pt => children.push(p(`✓ ${pt}`))); }
    if (miss.length) { children.push(h2(`Missed Points (${miss.length})`, 'dc2626')); miss.forEach(pt => children.push(p(`✗ ${pt}`))); }
    children.push(p(''));

    const ge = (a.grammarErrors as any[]) || [];
    if (ge.length) { children.push(h2('Grammar Errors', 'dc2626')); ge.forEach(e => { children.push(p(`✗ ${e.original}`, { color: 'dc2626' })); children.push(p(`→ ${e.correction}`, { color: '16a34a' })); if (e.explanation) children.push(p(`  ${e.explanation}`, { size: 18, color: '666666' })); }); children.push(p('')); }

    if (a.generalComment) { children.push(h2('AI Feedback', '2563eb')); children.push(p(String(a.generalComment))); if (a.generalCommentZh) children.push(p(String(a.generalCommentZh), { size: 18, color: '666666' })); children.push(p('')); }
    const tips = (a.improvementTips as string[]) || [];
    if (tips.length) { children.push(h2('Improvement Tips', '16a34a')); tips.forEach(t => children.push(p(`• ${t}`))); children.push(p('')); }
    if (a.modelAnswer) { children.push(h1('Model Answer (DSE Level 5)')); children.push(new Paragraph({ children: [new TextRun(String(a.modelAnswer))], border: { left: { style: BorderStyle.SINGLE, color: '7c3aed', size: 6 } }, spacing: { after: 200 } })); }
  }

  return Buffer.from(await Packer.toBuffer(new Document({ sections: [{ properties: {}, children }] })));
}

// ==================== PDF (pdfkit, English-only, no CJK dependency) ====================
async function generatePDF(data: ExportData): Promise<Buffer> {
  const PDFDocument = (await import('pdfkit')).default;
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    const doc = new PDFDocument({ size: 'A4', margins: { top: 40, bottom: 40, left: 50, right: 50 } }) as any;
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    let y = 40; const ml = 50, cw = 495, lh = 13;
    const cp = (n: number) => { if (y + n > 800) { doc.addPage(); y = 40; } };
    const wt = (text: string, x: number, yy: number, mw: number, lhV: number): number => {
      let line = '', cy = yy;
      for (const ch of text.split('')) {
        if (doc.widthOfString(line + ch) > mw && line.length > 0) { doc.text(line, x, cy); cy += lhV; line = ch; }
        else line += ch;
      }
      if (line) { doc.text(line, x, cy); cy += lhV; }
      return cy;
    };

    const section = (title: string) => { cp(30); doc.fontSize(13).fillColor('#0891b2').text(title, ml, y); y += 18; };
    const body = (text: string, size?: number, color?: string) => { doc.fontSize(size || 10).fillColor(color || '#333333'); y = wt(text, ml, y, cw, size ? size + 3 : 13) + 4; };

    // Title
    doc.fontSize(18).fillColor('#0f172a').text('DSE Integrated Skills Report', ml, y); y += 22;
    doc.fontSize(10).fillColor('#888888').text('Generated by AI English Platform', ml, y); y += 20;
    doc.moveTo(ml, y).lineTo(ml + cw, y).stroke('#cccccc'); y += 14;

    if (data.writingTask) { section('Writing Task'); body(data.writingTask); }
    if (data.listeningContent) { section('Listening Content'); body(data.listeningContent, 8, '#666666'); }
    if (data.studentNotes) { section('Student Note-taking'); body(data.studentNotes); }
    if (data.studentWriting) { section('Student Writing'); body(data.studentWriting); }

    const a = data.analysis;
    if (a) {
      section('AI Analysis');
      const scores = [['Overall Score', `${a.overallScore}%`], ['Listening Accuracy', `${a.listeningAccuracy ?? '-'}%`], ['Content Completeness', `${a.contentCompleteness ?? '-'}%`], ['Language Accuracy', `${a.languageAccuracy ?? '-'}%`], ['Organization & Clarity', `${a.organizationClarity ?? '-'}%`]];
      scores.forEach(([l, v]) => { cp(16); doc.fontSize(10).fillColor('#333333').text(l, ml, y); doc.fillColor('#059669').text(v, ml + 200, y); y += lh; });
      if (a.estimatedLevel) { doc.fillColor('#333333').text('Estimated Level', ml, y); doc.fillColor('#059669').text(String(a.estimatedLevel), ml + 200, y); y += lh; }
      y += 8;

      const caps = (a.capturedPoints as string[]) || [], miss = (a.missedPoints as string[]) || [];
      if (caps.length) { section('Captured Points'); caps.forEach(pt => { cp(16); doc.fontSize(9).fillColor('#16a34a').text(`✓ ${pt}`, ml + 5, y); y += lh; }); }
      if (miss.length) { section('Missed Points'); miss.forEach(pt => { cp(16); doc.fontSize(9).fillColor('#dc2626').text(`✗ ${pt}`, ml + 5, y); y += lh; }); }

      const ge = (a.grammarErrors as any[]) || [];
      if (ge.length) { section('Grammar Errors'); ge.forEach(e => { cp(30); doc.fontSize(9).fillColor('#dc2626').text(`✗ ${e.original}`, ml + 5, y); y += 11; doc.fillColor('#16a34a').text(`→ ${e.correction}`, ml + 10, y); y += 11; if (e.explanation) { doc.fontSize(8).fillColor('#666666').text(`  ${e.explanation}`, ml + 10, y); y += 10; } y += 4; }); }

      if (a.generalComment) { section('AI Feedback'); body(String(a.generalComment)); }
      const tips = (a.improvementTips as string[]) || [];
      if (tips.length) { section('Improvement Tips'); tips.forEach(t => { cp(16); doc.fontSize(9).fillColor('#16a34a').text(`• ${t}`, ml + 5, y); y += lh; }); }
      if (a.modelAnswer) { section('Model Answer (DSE Level 5)'); body(String(a.modelAnswer)); }
    }

    doc.end();
  });
}

export async function POST(request: NextRequest) {
  try {
    const data: ExportData = await request.json();
    if (!data.studentWriting && !data.analysis) {
      return NextResponse.json({ error: 'No content to export' }, { status: 400 });
    }

    const format = request.nextUrl.searchParams.get('format') || 'docx';

    if (format === 'pdf') {
      const buf = await generatePDF(data);
      return new NextResponse(new Uint8Array(buf), {
        headers: { 'Content-Type': 'application/pdf', 'Content-Disposition': 'attachment; filename="integrated-skills-report.pdf"' },
      });
    }

    const buf = await generateDOCX(data);
    return new NextResponse(new Uint8Array(buf), {
      headers: { 'Content-Type': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', 'Content-Disposition': 'attachment; filename="integrated-skills-report.docx"' },
    });
  } catch (error) {
    logger.error({ module: 'export-is', error: (error as Error).message }, 'Export failed');
    return NextResponse.json({ error: 'Export failed: ' + (error as Error).message }, { status: 500 });
  }
}
