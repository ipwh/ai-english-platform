// POST /api/export/integrated-skills
// 匯出 Integrated Skills 完整報告 (PDF + DOCX)
// 參照寫作分析 export 的 CJK 字型處理模式
// ============================================

import { NextRequest, NextResponse } from 'next/server';
import { verifyApiAuth } from '@/shared/auth/api-auth';
import { logger } from '@/shared/logger/logger';

interface ExportData {
  listeningContent?: string;
  dataFileSources?: { type: string; title: string; content: string }[];
  noteTakingGuide?: { question: string; hint: string; questionZh?: string; hintZh?: string }[];
  writingTask?: string; taskType?: string;
  studentNotes?: string; studentWriting?: string;
  analysis?: Record<string, unknown>;
}

function loadCJKFont(): Buffer | null {
  const path = require('node:path') as typeof import('node:path');
  const fs = require('node:fs') as typeof import('node:fs');
  const bundled = path.join(process.cwd(), 'public', 'fonts', 'NotoSansTC-Regular.ttf');
  if (fs.existsSync(bundled)) return fs.readFileSync(bundled);
  const candidates = ['C:\\Windows\\Fonts\\msjh.ttc', '/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc'];
  for (const fp of candidates) { try { if (fs.existsSync(fp)) return fs.readFileSync(fp); } catch { /* continue */ } }
  return null;
}

// ==================== PDF ====================
async function generatePDF(data: ExportData): Promise<Buffer> {
  const PDFDocument = (await import('pdfkit')).default;
  const fontData = loadCJKFont();
  if (!fontData) throw new Error('PDF export requires font file. Run: npx tsx scripts/download-font.ts');

  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    const doc = new PDFDocument({ size: 'A4', margin: 50, font: '', info: { Title: 'Integrated Skills Report' } }) as any;
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.registerFont('CJK', fontData);
    const f = 'CJK'; const cw = doc.page.width - 100; let y = 50;

    const checkPage = (n: number) => { if (y + n > doc.page.height - 50) { doc.addPage(); y = 50; } };
    const text = (t: string, size: number, color?: string, indent?: number, opts?: any) => {
      doc.font(f).fontSize(size).fillColor(color || '#1a1a1a');
      const x = 50 + (indent || 0);
      doc.text(t, x, y, { width: cw - (indent || 0), lineGap: 2, ...opts });
      y = doc.y + 4;
    };
    const heading = (t: string) => { checkPage(40); y += 6; text(t, 14, '#0891b2'); };

    text('DSE Integrated Skills Report', 18, '#1a5276');
    text('Generated by AI English Platform', 10, '#888888');
    doc.moveTo(50, y).lineTo(50 + cw, y).stroke('#cccccc'); y += 10;

    if (data.writingTask) { heading('Writing Task'); text(data.writingTask, 10, '#333333'); }
    if (data.listeningContent) { heading('Listening Content'); text(data.listeningContent, 8, '#666666'); }

    if (data.dataFileSources?.length) {
      heading('Data File');
      for (const src of data.dataFileSources) { text(`[${src.type}] ${src.title}`, 10, '#0891b2'); text(src.content, 8, '#666666'); }
    }

    if (data.noteTakingGuide?.length) {
      heading('Note-taking Guide');
      for (const item of data.noteTakingGuide) { text(`Q: ${item.question}`, 10, '#333333', 5); text(`Hint: ${item.hint}`, 8, '#888888', 10); }
    }

    if (data.studentNotes) { heading('Student Note-taking'); text(data.studentNotes, 10, '#f59e0b'); }
    if (data.studentWriting) { heading('Student Writing'); text(data.studentWriting, 10, '#7c3aed'); }

    const a = data.analysis;
    if (a) {
      heading('AI Analysis');
      const scores = [['Overall Score', `${a.overallScore}%`], ['Listening Accuracy', `${a.listeningAccuracy ?? '-'}%`], ['Content', `${a.contentCompleteness ?? '-'}%`], ['Language', `${a.languageAccuracy ?? '-'}%`], ['Organization', `${a.organizationClarity ?? '-'}%`]];
      scores.forEach(([l, v]) => { checkPage(16); text(`${l}: ${v}`, 10, '#333333', 5); });
      if (a.estimatedLevel) {
        text(`Estimated Level: ${a.estimatedLevel}`, 10, '#059669', 5);
        text('(Platform estimate — NOT an official HKEAA grade)', 7, '#888888', 8);
      }
      y += 4;

      const caps = (a.capturedPoints as string[]) || [], miss = (a.missedPoints as string[]) || [];
      if (caps.length) { heading('Captured Points'); caps.forEach(pt => text(`✓ ${pt}`, 9, '#16a34a', 5)); }
      if (miss.length) { heading('Missed Points'); miss.forEach(pt => text(`✗ ${pt}`, 9, '#dc2626', 5)); }

      const ge = (a.grammarErrors as any[]) || [];
      if (ge.length) { heading('Grammar Errors'); ge.forEach(e => { text(`✗ ${e.original}`, 9, '#dc2626', 5); text(`→ ${e.correction}`, 9, '#16a34a', 10); if (e.explanation) text(`  ${e.explanation}`, 8, '#666666', 10); }); }

      if (a.generalComment) { heading('AI Feedback'); text(String(a.generalComment), 10, '#333333'); }
      const tips = (a.improvementTips as string[]) || [];
      if (tips.length) { heading('Improvement Tips'); tips.forEach(t => text(`• ${t}`, 9, '#16a34a', 5)); }
      if (a.modelAnswer) { heading('Model Answer (Reference)'); text(String(a.modelAnswer), 10, '#7c3aed'); }
    }

    doc.end();
  });
}

// ==================== DOCX ====================
async function generateDOCX(data: ExportData): Promise<Buffer> {
  const { Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell, WidthType, BorderStyle } = await import('docx');
  const children: any[] = [];
  const h1 = (t: string) => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(t)], spacing: { before: 300, after: 100 } });
  const h2 = (t: string, c?: string) => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun({ text: t, color: c || '000000' })], spacing: { before: 200, after: 80 } });
  const p = (t: string, o?: any) => new Paragraph({ children: [new TextRun({ text: t, ...o })], spacing: { after: 80 } });
  const sep = () => children.push(new Paragraph({ spacing: { after: 120 }, children: [] }));

  children.push(new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun('DSE Integrated Skills Report')], spacing: { after: 100 } }));
  children.push(p('Generated by AI English Platform', { italics: true, color: '888888', size: 20 })); sep();

  if (data.writingTask) { children.push(h1('Writing Task')); children.push(p(`Type: ${data.taskType || 'N/A'}`)); children.push(p(data.writingTask)); sep(); }
  if (data.listeningContent) { children.push(h1('Listening Content')); children.push(p(data.listeningContent, { size: 18, color: '666666' })); sep(); }

  if (data.dataFileSources?.length) {
    children.push(h1('Data File'));
    for (const src of data.dataFileSources) { children.push(h2(`[${src.type}] ${src.title}`)); children.push(p(src.content, { size: 18, color: '666666' })); }
    sep();
  }

  if (data.noteTakingGuide?.length) {
    children.push(h1('Note-taking Guide'));
    for (const item of data.noteTakingGuide) { children.push(p(`Q: ${item.question}`, { bold: true })); children.push(p(`Hint: ${item.hint}`, { size: 18, color: '888888', italics: true })); }
    sep();
  }

  if (data.studentNotes) { children.push(h1('Student Note-taking')); children.push(new Paragraph({ children: [new TextRun(data.studentNotes)], border: { left: { style: BorderStyle.SINGLE, color: 'f59e0b', size: 6 } }, spacing: { after: 200 } })); sep(); }
  if (data.studentWriting) { children.push(h1('Student Writing')); children.push(new Paragraph({ children: [new TextRun(data.studentWriting)], border: { left: { style: BorderStyle.SINGLE, color: '7c3aed', size: 6 } }, spacing: { after: 200 } })); sep(); }

  const a = data.analysis;
  if (a) {
    children.push(h1('AI Analysis'));
    const scores: [string, string][] = [['Overall Score', `${a.overallScore}%`], ['Listening Accuracy', `${a.listeningAccuracy ?? '-'}%`], ['Content Completeness', `${a.contentCompleteness ?? '-'}%`], ['Language Accuracy', `${a.languageAccuracy ?? '-'}%`], ['Organization & Clarity', `${a.organizationClarity ?? '-'}%`]];
    if (a.estimatedLevel) {
      scores.push(['Estimated Level', String(a.estimatedLevel)]);
      scores.push(['Level Note', 'Platform estimate — NOT an official HKEAA grade']);
    }
    children.push(new Table({ rows: scores.map(([l, v]) => new TableRow({ children: [new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: l, bold: true })], spacing: { after: 0 } })], width: { size: 4500, type: WidthType.DXA } }), new TableCell({ children: [new Paragraph({ children: [new TextRun(v)], spacing: { after: 0 } })] })] })), width: { size: 100, type: WidthType.PERCENTAGE } })); sep();
    const caps = (a.capturedPoints as string[]) || [], miss = (a.missedPoints as string[]) || [];
    if (caps.length) { children.push(h2(`Captured Points (${caps.length})`, '16a34a')); caps.forEach(pt => children.push(p(`✓ ${pt}`))); }
    if (miss.length) { children.push(h2(`Missed Points (${miss.length})`, 'dc2626')); miss.forEach(pt => children.push(p(`✗ ${pt}`))); } sep();
    const ge = (a.grammarErrors as any[]) || [];
    if (ge.length) { children.push(h2('Grammar Errors', 'dc2626')); ge.forEach(e => { children.push(p(`✗ ${e.original}`, { color: 'dc2626' })); children.push(p(`→ ${e.correction}`, { color: '16a34a' })); if (e.explanation) children.push(p(`  ${e.explanation}`, { size: 18, color: '666666' })); }); sep(); }
    if (a.generalComment) { children.push(h2('AI Feedback', '2563eb')); children.push(p(String(a.generalComment))); if (a.generalCommentZh) children.push(p(String(a.generalCommentZh), { size: 18, color: '666666' })); sep(); }
    const tips = (a.improvementTips as string[]) || [];
    if (tips.length) { children.push(h2('Improvement Tips', '16a34a')); tips.forEach(t => children.push(p(`• ${t}`))); sep(); }
    if (a.modelAnswer) { children.push(h1('Model Answer (Reference)')); children.push(new Paragraph({ children: [new TextRun(String(a.modelAnswer))], border: { left: { style: BorderStyle.SINGLE, color: '7c3aed', size: 6 } }, spacing: { after: 200 } })); }
  }

  return Buffer.from(await Packer.toBuffer(new Document({ sections: [{ properties: {}, children }] })));
}

export async function POST(request: NextRequest) {
  // 🔒 R3.10-L: authenticate — this endpoint was previously unauthenticated.
  const authResult = await verifyApiAuth(request);
  if (!authResult.authenticated) {
    return NextResponse.json({ error: authResult.error }, { status: 401 });
  }

  try {
    const data: ExportData = await request.json();
    if (!data.studentWriting && !data.analysis) return NextResponse.json({ error: 'No content' }, { status: 400 });

    const fmt = request.nextUrl.searchParams.get('format') || 'pdf';
    const buf = fmt === 'docx' ? await generateDOCX(data) : await generatePDF(data);
    const ct = fmt === 'docx' ? 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' : 'application/pdf';
    const ext = fmt === 'docx' ? 'docx' : 'pdf';

    return new NextResponse(new Uint8Array(buf), {
      headers: { 'Content-Type': ct, 'Content-Disposition': `attachment; filename="integrated-skills-report.${ext}"` },
    });
  } catch (error) {
    logger.error({ module: 'export-is', error: (error as Error).message }, 'Export failed');
    return NextResponse.json({ error: 'Export failed: ' + (error as Error).message }, { status: 500 });
  }
}
