// ============================================
// Continuous Evaluation Report — Markdown report
// generation for monitoring results.
//
// Includes: summary, trend, regression analysis,
// alerts, provider health, and recommendations.
// ============================================

import type { MonitorRun } from './monitor';
import type { QualityTrend, WindowTrend } from './quality-trend';
import type { RegressionAssessment } from './regression-monitor';
import type { ProviderHealth } from './provider-monitor';
import type { Alert } from './alert';
import type { DriftReport } from './drift-detector';
import { DRIFT_ICONS, DRIFT_LABELS, ALERT_ICONS, ALERT_LABELS, TREND_LABELS } from './config';
import { PROVIDER_STATUS_ICONS } from './provider-monitor';

// ── Public API ──

/**
 * Generate a full continuous evaluation report in Markdown.
 */
export function generateContinuousReport(params: {
  runs: MonitorRun[];
  trends: QualityTrend[];
  providerHealth: ProviderHealth[];
  openAlerts: Alert[];
}): string {
  const { runs, trends, providerHealth, openAlerts } = params;
  const lines: string[] = [];

  lines.push('# 📡 Continuous Evaluation Report');
  lines.push(`**Generated:** ${new Date().toISOString()}`);
  lines.push(`**Runs:** ${runs.length} | **Prompts Monitored:** ${trends.length} | **Open Alerts:** ${openAlerts.length}`);
  lines.push('');

  // Summary
  lines.push(...generateSummarySection(runs, trends, openAlerts));
  lines.push('');

  // Trends
  lines.push(...generateTrendSection(trends));
  lines.push('');

  // Recent runs
  if (runs.length > 0) {
    lines.push(...generateRunSection(runs));
    lines.push('');
  }

  // Provider health
  if (providerHealth.length > 0) {
    lines.push(...generateProviderSection(providerHealth));
    lines.push('');
  }

  // Alerts
  if (openAlerts.length > 0) {
    lines.push(...generateAlertSection(openAlerts));
    lines.push('');
  }

  // Recommendations
  lines.push(...generateRecommendationsSection(runs, trends, openAlerts));

  lines.push('');
  lines.push('---');
  lines.push(`*Report auto-generated by Continuous Evaluation Platform*`);

  return lines.join('\n');
}

// ── Summary ──

function generateSummarySection(
  runs: MonitorRun[],
  trends: QualityTrend[],
  alerts: Alert[],
): string[] {
  const lines: string[] = ['## 📊 Summary', ''];

  // Overall health
  const decliningTrends = trends.filter(t => t.overallDirection === 'declining').length;
  const criticalAlerts = alerts.filter(a => a.severity === 'critical' && !a.resolved).length;
  const hasRegression = runs.some(r => r.regression.hasRegression);

  let healthStatus: string;
  if (criticalAlerts > 0 || decliningTrends > trends.length / 2) {
    healthStatus = '🔴 **Attention Required**';
  } else if (hasRegression || decliningTrends > 0) {
    healthStatus = '🟡 **Monitor Closely**';
  } else {
    healthStatus = '🟢 **Healthy**';
  }

  lines.push(`**Overall Health:** ${healthStatus}`);
  lines.push('');

  lines.push('| Metric | Value |');
  lines.push('|--------|-------|');
  lines.push(`| Monitored Prompts | ${trends.length} |`);
  lines.push(`| Recent Evaluations | ${runs.length} |`);
  lines.push(`| Regressions Detected | ${runs.filter(r => r.regression.hasRegression).length} |`);
  lines.push(`| Open Alerts | ${alerts.length} |`);
  lines.push(`| Critical Alerts | ${criticalAlerts} |`);
  lines.push(`| Declining Trends | ${decliningTrends} |`);

  return lines;
}

// ── Trends ──

function generateTrendSection(trends: QualityTrend[]): string[] {
  const lines: string[] = ['## 📈 Quality Trends', ''];

  if (trends.length === 0) {
    lines.push('*No trend data available.*');
    return lines;
  }

  lines.push('| Prompt | 7-Day | 30-Day | 90-Day | Overall | Peak? |');
  lines.push('|--------|-------|--------|--------|---------|-------|');

  for (const t of trends) {
    const peak = t.isAtPeak ? '🏔️' : t.isAtTrough ? '📉' : '';
    lines.push(
      `| ${t.promptName} | ${formatTrendCell(t.shortTerm)} | ${formatTrendCell(t.mediumTerm)} | ${formatTrendCell(t.longTerm)} | ${TREND_LABELS[t.overallDirection]} | ${peak} |`,
    );
  }

  lines.push('');
  lines.push('### Details');
  lines.push('');

  for (const t of trends) {
    if (t.shortTerm.recordCount === 0 && t.mediumTerm.recordCount === 0) continue;

    lines.push(`**${t.promptName}**`);
    lines.push(`- 7-day: ${t.shortTerm.movingAverage.toFixed(1)} (${t.shortTerm.recordCount} runs, slope: ${t.shortTerm.slope > 0 ? '+' : ''}${t.shortTerm.slope.toFixed(2)}/day)`);
    lines.push(`- 30-day: ${t.mediumTerm.movingAverage.toFixed(1)} | Best: ${t.mediumTerm.bestScore.toFixed(1)} | Worst: ${t.mediumTerm.worstScore.toFixed(1)}`);
    lines.push('');
  }

  return lines;
}

// ── Recent Runs ──

function generateRunSection(runs: MonitorRun[]): string[] {
  const lines: string[] = ['## 🔄 Recent Evaluations', ''];

  // Take last 20 runs
  const recent = runs.slice(-20).reverse();

  lines.push('| Prompt | Score | Drift | Regression | Alerts | Time |');
  lines.push('|--------|-------|-------|------------|--------|------|');

  for (const run of recent) {
    const driftIcon = run.drift
      ? DRIFT_ICONS[run.drift.overallSeverity]
      : '—';
    const regIcon = run.regression.hasRegression
      ? run.regression.severity === 'critical' ? '🔴' : '🟡'
      : '✅';
    const alertCount = run.alerts.length;

    lines.push(
      `| ${run.promptName} | ${run.record.overallScore.toFixed(1)} | ${driftIcon} | ${regIcon} | ${alertCount} | ${run.timestamp.slice(11, 19)} |`,
    );
  }

  return lines;
}

// ── Provider Health ──

function generateProviderSection(health: ProviderHealth[]): string[] {
  const lines: string[] = ['## 🌐 Provider Health', ''];

  lines.push('| Provider | Status | Success | Latency | Cost | JSON Repair |');
  lines.push('|----------|--------|---------|---------|------|-------------|');

  for (const h of health) {
    const icon = PROVIDER_STATUS_ICONS[h.status];
    lines.push(
      `| ${icon} ${h.provider} | ${h.status} | ${(h.successRate * 100).toFixed(1)}% | ${h.avgLatencyMs}ms | $${h.avgCostUsd.toFixed(5)} | ${(h.jsonRepairRate * 100).toFixed(1)}% |`,
    );
  }

  return lines;
}

// ── Alerts ──

function generateAlertSection(alerts: Alert[]): string[] {
  const lines: string[] = ['## 🚨 Open Alerts', ''];

  const critical = alerts.filter(a => a.severity === 'critical' && !a.resolved);
  const high = alerts.filter(a => a.severity === 'high' && !a.resolved);
  const warning = alerts.filter(a => a.severity === 'warning' && !a.resolved);

  if (critical.length > 0) {
    lines.push('### Critical');
    for (const a of critical) {
      lines.push(`- ${ALERT_ICONS.critical} **${a.title}** — ${a.description} (${a.createdAt.slice(0, 19)})`);
    }
    lines.push('');
  }

  if (high.length > 0) {
    lines.push('### High');
    for (const a of high) {
      lines.push(`- ${ALERT_ICONS.high} **${a.title}** — ${a.description}`);
    }
    lines.push('');
  }

  if (warning.length > 0) {
    lines.push('### Warning');
    for (const a of warning) {
      lines.push(`- ${ALERT_ICONS.warning} ${a.title} — ${a.description}`);
    }
    lines.push('');
  }

  if (critical.length === 0 && high.length === 0 && warning.length === 0) {
    lines.push('✅ No open alerts.');
  }

  return lines;
}

// ── Recommendations ──

function generateRecommendationsSection(
  runs: MonitorRun[],
  trends: QualityTrend[],
  alerts: Alert[],
): string[] {
  const lines: string[] = ['## 💡 Recommendations', ''];
  const recs: string[] = [];

  const criticalAlerts = alerts.filter(a => a.severity === 'critical' && !a.resolved);
  const decliningTrends = trends.filter(t => t.overallDirection === 'declining');

  if (criticalAlerts.length > 0) {
    recs.push('🔴 Address critical alerts immediately — structural failures and evaluation errors require prompt investigation.');
  }

  if (decliningTrends.length > 0) {
    const names = decliningTrends.map(t => t.promptName).join(', ');
    recs.push(`📉 Investigate declining quality for: ${names} — consider A/B testing prompt variants.`);
  }

  const regressionRuns = runs.filter(r => r.regression.hasRegression);
  if (regressionRuns.length > 0) {
    recs.push(`⚠️ ${regressionRuns.length} recent regression(s) detected — review recent prompt changes.`);
  }

  // Check for sustained issues
  for (const run of runs) {
    if (run.drift && run.drift.overallSeverity === 'critical') {
      recs.push(`🔴 Critical drift detected for ${run.promptName} — baseline comparison shows significant degradation.`);
    }
  }

  if (recs.length === 0) {
    recs.push('✅ All systems normal. No action required.');
  }

  for (const r of recs) {
    lines.push(`- ${r}`);
  }

  return lines;
}

// ── Helpers ──

function formatTrendCell(trend: WindowTrend): string {
  if (trend.recordCount === 0) return '—';
  const dir = trend.direction === 'improving' ? '↑' :
    trend.direction === 'declining' ? '↓' :
    trend.direction === 'volatile' ? '↕' : '→';
  return `${trend.movingAverage.toFixed(1)} ${dir}`;
}
