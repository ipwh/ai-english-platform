/**
 * 為 AI 出題 prompt 生成香港情境參考文本
 */
export function buildHKContextPrompt(category?: string, maxItems = 5): string {
  const allContexts = [
    ...Object.values(HK_DEMOGRAPHICS),
    ...Object.values(HK_LIFESTYLE),
    ...Object.values(HK_TECHNOLOGY),
    ...Object.values(HK_EDUCATION),
    ...Object.values(HK_ENVIRONMENT),
    ...Object.values(HK_CULTURE),
    ...Object.values(HK_WORKPLACE),
  ];

  const filtered = category
    ? allContexts.filter(c => c.topic.toLowerCase().includes(category.toLowerCase()))
    : allContexts;

  const selected = filtered.slice(0, maxItems);

  return selected.map(ctx =>
    `【${ctx.topicZh} (${ctx.topic})】
主要事實：
${ctx.keyFacts.map(f => `  • ${f}`).join('\n')}

可討論角度：
${ctx.discussionAngles.map(a => `  • ${a}`).join('\n')}

DSE Paper 2 相關：${ctx.dsePaper2Relevance}`
  ).join('\n\n---\n\n');
}

/**
 * 獲取隨機香港情境主題，用於出題多樣化
 */
export function getRandomHKContext(): {
  topic: string;
  topicZh: string;
  keyFact: string;
  discussionAngle: string;
} {
  const allContexts = [
    ...Object.values(HK_DEMOGRAPHICS),
    ...Object.values(HK_LIFESTYLE),
    ...Object.values(HK_TECHNOLOGY),
    ...Object.values(HK_EDUCATION),
    ...Object.values(HK_ENVIRONMENT),
    ...Object.values(HK_CULTURE),
    ...Object.values(HK_WORKPLACE),
  ];

  const ctx = allContexts[Math.floor(Math.random() * allContexts.length)];
  const fact = ctx.keyFacts[Math.floor(Math.random() * ctx.keyFacts.length)];
  const angle = ctx.discussionAngles[Math.floor(Math.random() * ctx.discussionAngles.length)];

  return {
    topic: ctx.topic,
    topicZh: ctx.topicZh,
    keyFact: fact,
    discussionAngle: angle,
  };
}
