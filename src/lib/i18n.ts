/**
 * 獲取翻譯文字
 * @param key 翻譯鍵
 * @param lang 語言代碼
 * @returns 翻譯後的文字
 */
export function t(key: string, lang?: string): string {
  const entry = translations[key];
  if (!entry) return key;
  return lang === 'en' ? entry.en : entry.zh;
}
